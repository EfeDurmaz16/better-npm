/**
 * Integration tests for v0.9 multi-ecosystem commands:
 * better migrate (all ecosystems), better plugin, offline mode,
 * cross-ecosystem monorepo, registry failover
 */
import test from "node:test";
import assert from "node:assert/strict";
import { execFile } from "node:child_process";
import { promisify } from "node:util";
import fs from "node:fs/promises";
import path from "node:path";
import { makeTempDir, rmrf, writeJson } from "./helpers.js";

const execFileAsync = promisify(execFile);
const betterBin = path.resolve(process.cwd(), "bin", "better.js");

async function runBetter(args, cwd) {
  return execFileAsync("node", [betterBin, ...args], {
    cwd: cwd || process.cwd(),
    env: { ...process.env, NO_COLOR: "1" },
    timeout: 20000,
  }).catch(err => ({ stdout: err.stdout || "", stderr: err.stderr || "", code: err.code }));
}

// ── better migrate ────────────────────────────────────────────────────────────

test("better migrate --help shows usage", async () => {
  const result = await runBetter(["migrate", "--help"]);
  assert.ok(
    result.stdout.includes("migrate") || result.stdout.includes("lock"),
    `Expected migrate help, got: ${result.stdout}`
  );
});

test("better migrate --json in a non-npm project returns structured output", async () => {
  const dir = await makeTempDir("better-migrate-");
  try {
    // Simulate a Cargo project
    await fs.writeFile(
      path.join(dir, "Cargo.toml"),
      '[package]\nname = "test-crate"\nversion = "0.1.0"\nedition = "2021"\n'
    );
    const result = await runBetter(["migrate", "--json"], dir);
    if (result.stdout && result.stdout.trim().startsWith("{")) {
      const parsed = JSON.parse(result.stdout.trim());
      assert.ok(typeof parsed === "object", "Expected JSON object");
    } else {
      // May fail gracefully if no source lockfile
      assert.ok(result.stdout.length > 0 || result.stderr.length > 0 || result.code !== 0);
    }
  } finally {
    await rmrf(dir);
  }
});

test("better migrate detects npm project type", async () => {
  const dir = await makeTempDir("better-migrate-npm-");
  try {
    await writeJson(path.join(dir, "package.json"), {
      name: "test-pkg", version: "1.0.0", dependencies: {}
    });
    // Create a yarn.lock
    await fs.writeFile(path.join(dir, "yarn.lock"), "# THIS IS AN AUTOGENERATED FILE.\n");
    const result = await runBetter(["migrate", "--json", "--from", "yarn"], dir);
    if (result.stdout && result.stdout.trim().startsWith("{")) {
      const parsed = JSON.parse(result.stdout.trim());
      assert.ok(typeof parsed === "object");
    } else {
      assert.ok(result.stdout.length > 0 || result.code !== 0);
    }
  } finally {
    await rmrf(dir);
  }
});

